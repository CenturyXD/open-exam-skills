def Q(
    question: str,
    options: list[str],
    correct_index: int,
    hint: str,
    correct_exp: str,
    wrong_exp: str | None = None,
) -> dict[str, Any]:
    return {
        "question": question,
        "options": options,
        "correctIndex": correct_index,
        "hint": hint,
        "correctExplanation": correct_exp,
        "wrongExplanation": wrong_exp or correct_exp,
    }


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.write("\n")


def write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content.rstrip() + "\n", encoding="utf-8")


def shuffle_options(correct: str, wrongs: list[str], seed: int) -> tuple[list[str], int]:
    rng = random.Random(seed)
    seen = {correct}
    unique_wrongs: list[str] = []
    for w in wrongs:
        if w not in seen:
            seen.add(w)
            unique_wrongs.append(w)
    while len(unique_wrongs) < 3:
        filler = f"ตัวเลือกที่ไม่ถูกต้อง ({len(unique_wrongs) + 1})"
        if filler not in seen:
            seen.add(filler)
            unique_wrongs.append(filler)
    options = [correct] + unique_wrongs[:3]
    rng.shuffle(options)
    return options, options.index(correct)


def facts_to_questions(facts: list[dict[str, Any]], bank_offset: int = 0) -> list[dict[str, Any]]:
    """Turn fact records into unique MCQs."""
    questions: list[dict[str, Any]] = []
    templates = [
        ("ข้อใดถูกต้องเกี่ยวกับ{topic}?", "answer"),
        ("{topic} ตอบข้อใดได้ถูกต้องที่สุด?", "answer"),
        ("ข้อใดไม่ถูกต้องเกี่ยวกับ{topic}?", "neg"),
        ("ตาม{law} ข้อใดตอบได้ถูกต้องที่สุดเรื่อง{topic}?", "answer"),
    ]
    for i, fact in enumerate(facts):
        topic = fact.get("topic", "เนื้อหาที่เกี่ยวข้อง")
        law = fact.get("law", "กฎหมายที่เกี่ยวข้อง")
        correct = fact["answer"]
        distractors = [f["answer"] for j, f in enumerate(facts) if j != i][:6]
        for t_idx, (tpl, mode) in enumerate(templates):
            if len(questions) >= QUESTIONS_PER_BANK:
                break
            seed = bank_offset * 1000 + i * 10 + t_idx
            stem = tpl.format(topic=topic, law=law)
            if mode == "answer":
                opts, ci = shuffle_options(correct, distractors, seed)
                exp = fact.get("explain", correct)
            else:
                wrong = fact.get("neg", f"ไม่เกี่ยวข้องกับ{topic}")
                opts, ci = shuffle_options(wrong, [correct] + distractors[:2], seed + 1)
                exp = f"ข้อที่ไม่ถูกต้องคือ: {wrong}"
            questions.append(
                Q(
                    stem,
                    opts,
                    ci,
                    fact.get("hint", topic),
                    exp,
                )
            )
        if len(questions) >= QUESTIONS_PER_BANK:
            break
    return questions[:QUESTIONS_PER_BANK]


def build_quiz(title: str, bank_specs: list[tuple[str, str, list[dict]]]) -> dict[str, Any]:
    banks = []
    for idx, (bank_id, bank_title, facts) in enumerate(bank_specs, start=1):
        qs = facts_to_questions(facts, bank_offset=idx)
        if len(qs) < QUESTIONS_PER_BANK:
            raise ValueError(f"Bank {bank_id} has only {len(qs)} questions, need {QUESTIONS_PER_BANK}")
        banks.append(
            {
                "id": bank_id,
                "title": f"{bank_title} ({QUESTIONS_PER_BANK} ข้อ)",
                "questions": qs,
            }
        )
    return {"title": title, "banks": banks}


def build_flashcards(title: str, cards: list[tuple[str, str]]) -> dict[str, Any]:
    return {
        "title": title,
        "flashcards": [{"question": q, "answer": a} for q, a in cards[:FLASHCARD_COUNT]],
    }


