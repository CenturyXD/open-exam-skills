def verify_quiz(path: Path) -> tuple[bool, str]:
    if not path.exists():
        return False, "ไฟล์ไม่มี"
    data = json.loads(path.read_text(encoding="utf-8"))
    banks = data.get("banks", [])
    if len(banks) != BANK_COUNT:
        return False, f"มี {len(banks)} ชุด (ต้องการ {BANK_COUNT})"
    for bank in banks:
        qs = bank.get("questions", [])
        if len(qs) != QUESTIONS_PER_BANK:
            return False, f"{bank.get('id')}: {len(qs)} ข้อ (ต้องการ {QUESTIONS_PER_BANK})"
        for i, q in enumerate(qs):
            opts = q.get("options", [])
            ci = q.get("correctIndex")
            if len(opts) != 4:
                return False, f"{bank.get('id')} ข้อ {i+1}: มี {len(opts)} ตัวเลือก"
            if ci not in (0, 1, 2, 3):
                return False, f"{bank.get('id')} ข้อ {i+1}: correctIndex={ci}"
            required = {"question", "options", "correctIndex", "hint", "correctExplanation", "wrongExplanation"}
            if not required.issubset(q.keys()):
                return False, f"{bank.get('id')} ข้อ {i+1}: ขาดฟิลด์"
    return True, f"{BANK_COUNT}×{QUESTIONS_PER_BANK} = {BANK_COUNT * QUESTIONS_PER_BANK} ข้อ"


def verify_flashcards(path: Path) -> tuple[bool, str]:
    if not path.exists():
        return False, "ไฟล์ไม่มี"
    data = json.loads(path.read_text(encoding="utf-8"))
    cards = data.get("flashcards", [])
    if len(cards) != FLASHCARD_COUNT:
        return False, f"มี {len(cards)} ใบ (ต้องการ {FLASHCARD_COUNT})"
    return True, f"{FLASHCARD_COUNT} ใบ"


def print_summary() -> None:
    print("\n" + "=" * 60)
    print("สรุปการตรวจสอบชุดเรียน")
    print("=" * 60)
    all_slugs = list(TOPICS.keys()) + ["court-of-justice-admin"]
    ok_all = True
    for slug in all_slugs:
        pack_dir = STUDY_DIR / slug
        quiz_ok, quiz_msg = verify_quiz(pack_dir / "quiz.json")
        status = "OK" if quiz_ok else "FAIL"
        if not quiz_ok:
            ok_all = False
        print(f"  [{status}] {slug}/quiz.json — {quiz_msg}")
        if slug in TOPICS:
            fc_ok, fc_msg = verify_flashcards(pack_dir / "flashcards.json")
            status = "OK" if fc_ok else "FAIL"
            if not fc_ok:
                ok_all = False
            for fname in ("SUMMARY.md", "SOURCES.md", "mindmap.md", "README.md"):
                exists = (pack_dir / fname).exists()
                st = "OK" if exists else "FAIL"
                if not exists:
                    ok_all = False
                print(f"  [{st}] {slug}/{fname}")
            print(f"  [{status}] {slug}/flashcards.json — {fc_msg}")
    print("=" * 60)
    if ok_all:
        print("ผลรวม: ผ่านทั้งหมด")
    else:
        print("ผลรวม: มีข้อผิดพลาด — ตรวจสอบด้านบน")
        raise SystemExit(1)


