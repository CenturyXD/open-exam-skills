def generate_pack(slug: str, config: dict[str, Any]) -> None:
    pack_dir = STUDY_DIR / slug
    pack_dir.mkdir(parents=True, exist_ok=True)
    title = config["title"]

    quiz = build_quiz(title, config["banks"])
    write_json(pack_dir / "quiz.json", quiz)

    write_text(pack_dir / "SUMMARY.md", config["summary"])
    write_text(pack_dir / "mindmap.md", config["mindmap"])
    write_text(pack_dir / "SOURCES.md", sources_template(title, config["sources_docs"], config["sources_scope"]))
    write_json(pack_dir / "flashcards.json", build_flashcards(title, config["flashcards"]))
    write_text(pack_dir / "README.md", readme_for(slug, title, config["readme_scope"]))


